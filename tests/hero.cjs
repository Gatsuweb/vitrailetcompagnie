const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Découvrir',exact:true}).click();
 await page.waitForTimeout(1700);
 await page.locator('h1').waitFor();
 await page.waitForTimeout(1800);
 assert.equal(await page.locator('[data-depth] img').count(),3);
 assert(await page.locator('[data-depth] img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0)));
 await page.screenshot({path:'tests/desktop.png'});
 const transforms=()=>page.locator('[data-depth]').evaluateAll(els=>els.map(el=>{const m=new DOMMatrix(getComputedStyle(el).transform);return {x:m.m41,y:m.m42};}));
 await page.mouse.move(1350,450); await page.waitForTimeout(200);
 const early=await transforms();
 assert(early[2].x/10-early[1].x/5>.15, "Foreground should respond faster than middle, independently of amplitude");
 await page.waitForTimeout(1400);
 const moved=await transforms(); assert(moved[0].x<0&&moved[1].x>0&&moved[2].x>moved[1].x);
 await page.evaluate(()=>window.scrollTo({top:70,behavior:'instant'})); await page.mouse.move(1400,890); await page.waitForTimeout(1600);
 const scrolled=await transforms(); assert(scrolled[2].y>scrolled[1].y&&scrolled[1].y>scrolled[0].y);
 await page.emulateMedia({reducedMotion:'reduce'}); await page.waitForTimeout(600);
 const still=await transforms(); console.log({still}); assert(still.every(t=>t.x===0&&t.y===0));
 await page.locator('a').filter({hasText:'Découvrir les créations'}).click();
 assert.equal(new URL(page.url()).hash,'#creations');
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
 await mobile.goto('http://localhost:3000',{waitUntil:'networkidle'}); await mobile.getByRole('button',{name:'Découvrir',exact:true}).click(); await mobile.waitForTimeout(1100); await mobile.waitForTimeout(1800);
 assert(await mobile.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
 await mobile.screenshot({path:'tests/mobile.png'});
 await mobile.mouse.move(350,400); await mobile.waitForTimeout(300);
 assert(await mobile.locator('[data-depth]').evaluateAll(els=>els.every(el=>new DOMMatrix(getComputedStyle(el).transform).m41===0)));
 assert.equal(errors.length,0,errors.join('\n'));
 console.log('PASS: images, desktop pointer, scroll depths, reduced motion, CTA, mobile layout and disabled mobile pointer; no runtime errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
